"""Generate the schema reference pages and the JSON model for one WSD service package.

Everything is derived from :mod:`fakeprint.wsd_schema` (never from hand-parsed XML) and driven by
a :class:`fakeprint.services.ServiceProfile`; this file names no service, element or fault.

The output is mechanically derived from Microsoft's schemas, so it is written into the ignored
``docs/reference/schema`` directory and must never be committed or redistributed. The hand-written
notes under ``docs/reference/*.md`` are the tracked counterpart.

Usage::

    fakeprint-refs                      # print service, default locations
    fakeprint-refs --service scan       # same code, scan package
    fakeprint-refs --schema-dir X --out-dir Y
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from . import services
from . import wsd_schema as w
from .wsd_schema import ComplexType, QName, SchemaSet, SimpleType

__all__ = ["build", "generate_reference_docs", "main"]

GENERATED_BANNER = (
    "<!-- Generated by fakeprint-refs from the Microsoft WSD schemas. Derived from licensed material: "
    "do not commit or redistribute. -->"
)


def _occ(mn: int, mx: int | None) -> str:
    return f"{mn}..{'*' if mx is None else mx}"


def _esc(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ").strip()


def _first_sentence(doc: str, limit: int = 160) -> str:
    one = " ".join(doc.split())
    return one if len(one) <= limit else one[: limit - 3] + "..."


class _Gen:
    def __init__(self, ss: SchemaSet, profile: services.ServiceProfile, out: Path) -> None:
        self.ss, self.profile, self.out = ss, profile, out
        self.files: dict[QName, str] = {}
        self._assign_type_files()
        self.usage = ss.usages()
        self.written: list[Path] = []

    # ---- naming -------------------------------------------------------------------------
    def _assign_type_files(self) -> None:
        by_local: dict[str, list[QName]] = {}
        for qn in [*self.ss.complex_types, *self.ss.simple_types]:
            by_local.setdefault(qn[1], []).append(qn)
        for local, qns in by_local.items():
            for qn in qns:
                if len(qns) == 1:
                    self.files[qn] = f"{local}.md"
                else:
                    self.files[qn] = f"{self.ss.qstr(qn).replace(':', '.')}.md"

    def link(self, qn: QName | None, up: str = "", text: str | None = None) -> str:
        if qn is None:
            return "text"
        label = text or self.ss.qstr(qn)
        if qn in self.files:
            return f"[{label}]({up}types/{self.files[qn]})"
        return f"`{label}`"

    def write(self, rel: str, text: str) -> None:
        p = self.out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(GENERATED_BANNER + "\n" + text.rstrip() + "\n", encoding="utf-8")
        self.written.append(p)

    # ---- pieces -------------------------------------------------------------------------
    def attr_table(self, ct: ComplexType, up: str) -> list[str]:
        ss = self.ss
        attrs = ss.effective_attributes(ct)
        any_attr = ss.effective_any_attribute(ct)
        if not attrs and any_attr is None:
            return []
        lines = ["**Attributes**", "", "| Name | Type | Use | Default | Declared in |", "| --- | --- | --- | --- | --- |"]
        for a, where in attrs:
            ty = ss.attribute_type(a)
            if isinstance(ty, SimpleType):
                tdesc = ss.simple_info(ty).label()
            elif ty is not None:
                tdesc = self.link(ty, up)
            else:
                tdesc = "string"
            default = ss.attribute_default(a)
            lines.append(f"| `{ss.qstr(a.name)}`{' (global)' if a.is_ref else ''} | {tdesc} | {a.use} | "
                         f"{_esc(default) if default is not None else ''} | {self.link(where, up) if where else ''} |")
        if any_attr is not None:
            lines.append(f"| *any attribute* | wildcard `{any_attr.namespace}` | optional | | "
                         f"processContents={any_attr.process_contents} |")
        lines.append("")
        return lines

    def row_table(self, ct: ComplexType, up: str) -> list[str]:
        ss = self.ss
        rows = ss.effective_rows(ct)
        if not rows:
            return []
        lines = ["**Content model** (document order, base type first)", "",
                 "| Element | Type | Occurs | Required | Group | Declared in | Notes |",
                 "| --- | --- | --- | --- | --- | --- | --- |"]
        for r in rows:
            p = r.particle
            if p.kind == "any":
                lines.append(f"| *any element* | wildcard `{p.namespace}` | {_occ(r.min_occurs, r.max_occurs)} | no | "
                             f"{r.choice or ''} | {self.link(r.declared_in, up) if r.declared_in else ''} | "
                             f"vendor extension point, processContents={p.process_contents} |")
                continue
            tqn, tobj, g = ss._deref_particle_element(p)
            if p.anon_type is not None:
                tdesc = "(anonymous " + ("complex" if isinstance(p.anon_type, ComplexType) else "simple") + ")"
            elif tqn is not None:
                tdesc = self.link(tqn, up)
            else:
                tdesc = "(none)"
            notes = []
            if p.is_ref:
                notes.append("global element ref")
            if p.doc_attributes:
                notes.append("documented attributes: " + ", ".join(p.doc_attributes))
            if p.doc and not (p.doc_attributes and re.match(r"^\s*Attributes?\s*:", p.doc, re.I)):
                notes.append(_first_sentence(p.doc))
            if p.nillable:
                notes.append("nillable")
            if p.fixed is not None:
                notes.append(f"fixed={p.fixed}")
            lines.append(f"| `{ss.qstr(p.name)}` | {tdesc} | {_occ(r.min_occurs, r.max_occurs)} | "
                         f"{'yes' if r.min_occurs >= 1 else 'no'} | {r.choice or ''} | "
                         f"{self.link(r.declared_in, up) if r.declared_in else ''} | {_esc('; '.join(notes))} |")
        lines.append("")
        return lines

    def enum_table(self, t, up: str = "") -> list[str]:
        vals = self.ss.enumeration(t)
        if not vals:
            return []
        has_doc = any(d for _, d, _ in vals)
        head = "| Value | Declared in |" + (" Documentation |" if has_doc else "")
        lines = ["**Enumerated values**", "", head, "| --- | --- |" + (" --- |" if has_doc else "")]
        for v, d, where in vals:
            lines.append(f"| `{_esc(v)}` | {where} |" + (f" {_esc(d)} |" if has_doc else ""))
        lines.append("")
        return lines

    def type_body(self, qn: QName, level: str, up: str) -> list[str]:
        ss = self.ss
        ct = ss.complex_types.get(qn)
        st = ss.simple_types.get(qn)
        lines = [f"{level} {ss.qstr(qn)}", ""]
        if ct is not None:
            lines.append(f"- **Kind:** complexType, content `{ct.content}`" + (", abstract" if ct.abstract else "")
                         + (", mixed" if ct.mixed else ""))
            if ct.base:
                lines.append(f"- **{ct.derivation or 'Derived from'} of:** {self.link(ct.base, up)}")
            lines.append(f"- **Declared in:** `{Path(ct.source).name}`")
            if ct.content == "simple":
                lines.append(f"- **Value:** `{ss.simple_info(ct).label()}`")
            if ct.doc:
                lines += ["", ct.doc]
            lines.append("")
            lines += self.attr_table(ct, up)
            lines += self.row_table(ct, up)
            if ct.content == "simple":
                lines += self.enum_table(ct, up)
        elif st is not None:
            info = ss.simple_info(st)
            lines.append(f"- **Kind:** simpleType ({st.variety})")
            lines.append(f"- **Declared in:** `{Path(st.source).name}`")
            lines.append(f"- **Value space:** `{info.label()}`")
            if st.variety == "union":
                lines.append("- **Union members:** " + ", ".join(
                    self.link(m, up) if isinstance(m, tuple) else "(anonymous)" for m in st.members))
            elif st.base:
                lines.append(f"- **Restricts:** {self.link(st.base, up)}")
            if info.chain:
                lines.append("- **Derivation chain:** " + " -> ".join(info.chain))
            f = info.facets
            for label, v in (("length", f.length), ("minLength", f.min_length), ("maxLength", f.max_length),
                             ("minInclusive", f.min_inclusive), ("maxInclusive", f.max_inclusive),
                             ("whiteSpace", f.white_space)):
                if v is not None:
                    lines.append(f"- **{label}:** {v}")
            if st.doc:
                lines += ["", st.doc]
            lines.append("")
            pats = ss.patterns(st)
            if pats:
                lines += ["**Patterns** (any one must match)", ""] + [f"- `{_esc(p)}`" for p in pats] + [""]
            lines += self.enum_table(st, up)
        uses = self.usage.get(qn, [])
        if uses:
            lines += ["**Used by**", ""]
            for kind, user in sorted(set(uses))[:40]:
                lines.append(f"- {kind}: `{user}`")
            if len(set(uses)) > 40:
                lines.append(f"- ... and {len(set(uses)) - 40} more")
            lines.append("")
        return lines

    def outline(self, t, depth: int, seen: tuple, up: str, lines: list[str], indent: int = 0) -> None:
        """Nested bullet outline of an element's shape; wildcards and recursion are marked."""
        ss = self.ss
        if isinstance(t, tuple):
            t = ss.lookup_type(t)
        if not isinstance(t, ComplexType) or depth <= 0 or (t.qname in seen):
            return
        pad = "  " * indent
        for a, _ in ss.effective_attributes(t):
            lines.append(f"{pad}- @{ss.qstr(a.name)} ({a.use})")
        for r in ss.effective_rows(t):
            p = r.particle
            if p.kind == "any":
                lines.append(f"{pad}- *any* `{p.namespace}` [{_occ(r.min_occurs, r.max_occurs)}]")
                continue
            tqn, tobj, _g = ss._deref_particle_element(p)
            tdesc = ss.qstr(tqn) if tqn else "(anonymous)"
            info = ""
            if isinstance(tobj, SimpleType) or (isinstance(tobj, ComplexType) and tobj.content == "simple") or (tqn and ss.is_builtin(tqn)):
                info = " = " + ss.simple_info(tqn if tqn else tobj).label()
            ch = f" (choice)" if r.choice else ""
            lines.append(f"{pad}- `{ss.qstr(p.name)}` : {tdesc} [{_occ(r.min_occurs, r.max_occurs)}]{ch}{info}")
            if isinstance(tobj, ComplexType):
                self.outline(tobj, depth - 1, (*seen, t.qname), up, lines, indent + 1)

    # ---- pages --------------------------------------------------------------------------
    def type_pages(self) -> None:
        for qn in sorted([*self.ss.complex_types, *self.ss.simple_types]):
            self.write(f"types/{self.files[qn]}", "\n".join(self.type_body(qn, "#", "../")))

    def file_pages(self) -> list[tuple[str, str, int, int]]:
        ss, prof = self.ss, self.profile
        docs = [d for d in ss.docs if d.embedded_in is None]
        order = {n: i for i, n in enumerate(prof.file_order)}
        docs.sort(key=lambda d: (order.get(Path(d.source).stem, len(order)), Path(d.source).name.lower()))
        pages = []
        for n, d in enumerate(docs, 1):
            stem = Path(d.source).stem
            page = f"{n:02d}-{stem}.md"
            tys = sorted(q for q, t in [*ss.complex_types.items(), *ss.simple_types.items()] if t.source == d.source)
            els = sorted(q for q, e in ss.elements.items() if e.source == d.source)
            lines = [f"# {Path(d.source).name}", "", f"- **Target namespace:** `{d.target_ns}`",
                     f"- **Includes:** {', '.join(f'`{i}`' for i in d.includes) or 'none'}",
                     f"- **Imports:** {', '.join(f'`{n}` <- `{l}`' for n, l in d.imports) or 'none'}",
                     f"- **{len(tys)} named types, {len(els)} global elements**", ""]
            if d.doc:
                lines += [d.doc, ""]
            if els:
                lines += ["## Global elements", "", "| Element | Type | Substitution group | Documentation |", "| --- | --- | --- | --- |"]
                for q in els:
                    e = ss.elements[q]
                    t = self.link(e.type) if e.type else "(anonymous)"
                    lines.append(f"| `{ss.qstr(q)}` | {t} | {ss.qstr(e.substitution_group) if e.substitution_group else ''} | {_esc(_first_sentence(e.doc))} |")
                lines.append("")
            for q in tys:
                lines += self.type_body(q, "##", "")
            self.write(page, "\n".join(lines))
            pages.append((page, Path(d.source).name, len(tys), len(els)))
        return pages

    def operation_pages(self) -> dict[str, list]:
        ss = self.ss
        views = ss.operations()
        ops_index: dict[str, list] = {"ops": [], "events": [], "ext": []}
        used = set()
        for v in views:
            used.add(v.name)
            kind = "events" if v.kind == "notification" else "ops"
            ops_index[kind].append((v.name, v.kind, ss.qstr(v.input_element), ss.qstr(v.output_element), v.soap_action or "", v.input_action or v.output_action or ""))
            self.write(f"operations/{v.name}.md", "\n".join(self._op_page(v)))
        # message-only elements (extension schemas without a usable WSDL binding)
        groups: dict[str, dict[str, QName]] = {}
        for qn in ss.orphan_message_elements():
            m = re.match(r"^(.*?)(Request|Response|Event)$", qn[1])
            if m:
                groups.setdefault(m.group(1) or qn[1], {})[m.group(2)] = qn
        for base, parts in sorted(groups.items()):
            if base in used:
                continue
            lines = [f"# {base} (message elements only)", "",
                     "- **Source:** global elements in the schema; **no WSDL operation and no wsa:Action in the package**.",
                     f"- **Namespace:** `{next(iter(parts.values()))[0]}`",
                     "- **Action URI:** unknown from the package (the prose specification, not the schema, defines it)", ""]
            for role, qn in sorted(parts.items()):
                lines += [f"## {role}: `{ss.qstr(qn)}`", ""]
                el = ss.elements[qn]
                if el.type:
                    lines += [f"Type: {self.link(el.type, '../')}", ""]
                    self.outline(el.type, 6, (), "../", lines)
                    lines.append("")
            self.write(f"operations/{base}.md", "\n".join(lines))
            ops_index["ext"].append((base, ", ".join(sorted(parts)), ss.qstr(parts.get("Request")), ss.qstr(parts.get("Response") or parts.get("Event"))))
        # absent-operation probe (data-driven)
        names = {n for n in used} | {b for b in groups}
        ops_index["probe"] = [(n, n in names or any(q[1] == n for q in ss.elements)) for n in self.profile.probe_operations]
        idx = ["# Operations", "", "Derived from the WSDL portTypes/bindings in the package (and message-only elements of extension schemas).", ""]
        if ops_index["ops"]:
            idx += ["## Request/response operations", "", "| Operation | Kind | Request | Response | soapAction | wsa:Action (input) |", "| --- | --- | --- | --- | --- | --- |"]
            for n, k, i, o, sa, act in ops_index["ops"]:
                idx.append(f"| [{n}]({n}.md) | {k} | `{i}` | `{o}` | {sa or '*none in package*'} | {act} |")
            idx.append("")
        if ops_index["events"]:
            idx += ["## Events (notification operations, event source)", "", "| Event | Body element | Action |", "| --- | --- | --- |"]
            for n, k, i, o, sa, act in ops_index["events"]:
                idx.append(f"| [{n}]({n}.md) | `{o}` | {act} |")
            idx.append("")
        if ops_index["ext"]:
            idx += ["## Extension messages without a WSDL operation", "", "| Name | Roles | Request | Response/Event |", "| --- | --- | --- | --- |"]
            for n, roles, i, o in ops_index["ext"]:
                idx.append(f"| [{n}]({n}.md) | {roles} | `{i}` | `{o}` |")
            idx.append("")
        if ops_index["probe"]:
            idx += ["## Expected administrative operations: present in this package?", "", "| Name | Present |", "| --- | --- |"]
            for n, ok in ops_index["probe"]:
                idx.append(f"| {n} | {'yes' if ok else 'no'} |")
            idx.append("")
        self.write("operations/index.md", "\n".join(idx))
        return ops_index

    def _op_page(self, v: w.OperationView) -> list[str]:
        ss = self.ss
        lines = [f"# {v.name}", "", f"- **Kind:** {v.kind}" + (" (event source portType)" if v.event_source else ""),
                 f"- **PortType:** `{ss.qstr(v.port_type)}`", f"- **WSDL:** `{Path(v.wsdl).name}`",
                 f"- **soapAction (binding):** {v.soap_action or '*not resolvable from the package*'}"
                 + ("" if v.soap_action_required is None else f" (required={str(v.soap_action_required).lower()})"),
                 f"- **wsa:Action input:** {v.input_action or '-'}", f"- **wsa:Action output:** {v.output_action or '-'}"]
        if v.doc:
            lines += ["", v.doc]
        lines.append("")
        for role, el in (("Request", v.input_element), ("Response" if v.kind != "notification" else "Event body", v.output_element)):
            if el is None:
                continue
            decl = ss.elements.get(el)
            lines += [f"## {role}: `{ss.qstr(el)}`", ""]
            if decl is not None and decl.type:
                lines += [f"Type: {self.link(decl.type, '../')}", ""]
                self.outline(decl.type, 6, (), "../", lines)
                lines.append("")
            ct = ss.complex_types.get(decl.type) if decl is not None and decl.type else None
            if ct is not None:
                lines += self.row_table(ct, "../")
        lines += ["## Faults", "", "The WSDL declares no fault messages for this operation. Fault subcodes come from "
                  "the service's fault enumeration, see [faults](../faults.md); situations are in the hand-written notes.", ""]
        return lines

    def concept_pages(self) -> list[str]:
        ss = self.ss
        made = []
        for name in self.profile.concepts:
            cands_t = [q for q in [*ss.complex_types, *ss.simple_types] if q[1] in (name, name + "Type", name + "WKVType", name + "BaseType", name + "ExtType")]
            cands_e = [q for q in ss.elements if q[1] == name]
            local_users = []
            for qn, ct in ss.complex_types.items():
                for r in ss.effective_rows(ct):
                    p = r.particle
                    if p.kind == "element" and p.name and p.name[1] == name and r.declared_in == qn:
                        local_users.append((qn, p))
            if not (cands_t or cands_e or local_users):
                continue
            lines = [f"# {name}", ""]
            if cands_e:
                lines += ["**Global element(s):** " + ", ".join(f"`{ss.qstr(q)}`" for q in cands_e), ""]
            if local_users:
                lines += ["**Used as a child element of**", "", "| Parent type | Element type | Occurs | Notes |", "| --- | --- | --- | --- |"]
                for qn, p in local_users:
                    tq = p.type
                    lines.append(f"| {self.link(qn, '../')} | {self.link(tq, '../') if tq else '(anonymous)'} | {_occ(p.min_occurs, p.max_occurs)} | "
                                 f"{_esc('; '.join(filter(None, [('documented attributes: ' + ', '.join(p.doc_attributes)) if p.doc_attributes else '', _first_sentence(p.doc)])))} |")
                lines.append("")
            chain = list(dict.fromkeys([*[p.type for _, p in local_users if p.type], *cands_t]))
            for qn in chain:
                if qn in self.files:
                    lines += self.type_body(qn, "##", "../")
                    # follow type chain once: members of unions and bases that carry enumerations
                    st = ss.simple_types.get(qn)
                    ct = ss.complex_types.get(qn)
                    nxt = [m for m in (st.members if st else []) if isinstance(m, tuple)] + ([ct.base] if ct and ct.base else [])
                    for sub in nxt:
                        if sub in self.files and sub not in chain:
                            lines += self.type_body(sub, "###", "../")
            self.write(f"concepts/{name}.md", "\n".join(lines))
            made.append(name)
        return made

    def faults_page(self) -> None:
        ss = self.ss
        lines = ["# Fault codes", "",
                 "Subcodes enumerated by the schema (xs:QName enumerations of prefixed names). The WSDL declares no fault "
                 "messages, and the schema does not say which operation raises which code; see the hand-written "
                 "`docs/reference/faults.md` for situations.", ""]
        enums = ss.fault_enumerations()
        if not enums:
            lines.append("No QName-valued fault enumeration found in this package.")
        for t, vals in enums:
            lines += [f"## {ss.qstr(t)}", "", "| Subcode | Namespace | Local name | Documentation |", "| --- | --- | --- | --- |"]
            for (ns, local), d in vals:
                lines.append(f"| `{ss.qstr((ns, local))}` | {ns} | {local} | {_esc(d)} |")
            lines.append("")
        self.write("faults.md", "\n".join(lines))

    def enumerations_page(self) -> None:
        ss = self.ss
        lines = ["# All enumerations", "", "Every simple type (or simple-content type) with enumerated values, flattened through unions.", ""]
        n = 0
        for qn in sorted([*ss.simple_types, *ss.complex_types]):
            t = ss.simple_types.get(qn) or ss.complex_types[qn]
            vals = ss.enumeration(t)
            if not vals:
                continue
            n += 1
            lines += [f"## {ss.qstr(qn)}", "", ", ".join(f"`{v}`" for v, _d, _w in vals), ""]
            pats = ss.patterns(t)
            if pats:
                lines += [f"Also accepts pattern-matched extension values ({len(pats)} pattern(s)); see {self.link(qn, '')}.", ""]
        self.write("enumerations.md", "\n".join(lines))

    def attributes_page(self) -> None:
        ss = self.ss
        lines = ["# Attributes", "", "## Global attributes", "", "| Attribute | Type | Default | Used by |", "| --- | --- | --- | --- |"]
        for qn, a in sorted(ss.attributes.items()):
            users = sorted({u for k, u in self.usage.get(qn, []) if k == "attribute-ref"})
            lines.append(f"| `{ss.qstr(qn)}` | {ss.qstr(a.type) if a.type else 'inline'} | {a.default if a.default is not None else ''} | "
                         f"{len(users)} type(s): {_esc(', '.join(u.split('/')[0] for u in users[:12]))}{' ...' if len(users) > 12 else ''} |")
        lines += ["", "## Local (declared on a type)", "", "| Type | Attribute | Type | Use |", "| --- | --- | --- | --- |"]
        for qn, ct in sorted(ss.complex_types.items()):
            for a in ct.attributes:
                if not a.is_ref:
                    lines.append(f"| {self.link(qn)} | `{ss.qstr(a.name)}` | {ss.qstr(a.type) if a.type else 'inline'} | {a.use} |")
        lines += ["", "## Elements whose documentation names attributes", "", "(schema convention: the annotation of an element says which attribute it may carry)", "",
                  "| Parent | Element | Attributes named |", "| --- | --- | --- |"]
        for qn, ct in sorted(ss.complex_types.items()):
            for r in ss.effective_rows(ct):
                if r.declared_in == qn and r.particle.doc_attributes:
                    lines.append(f"| {self.link(qn)} | `{ss.qstr(r.particle.name)}` | {', '.join(r.particle.doc_attributes)} |")
        self.write("attributes.md", "\n".join(lines))

    def extension_page(self) -> None:
        ss = self.ss
        pts = ss.extension_points()
        lines = ["# Extension points (xs:any / xs:anyAttribute)", "",
                 f"{len(pts)} wildcards. `##other` means: any element/attribute from a namespace other than the target namespace "
                 "(vendor extensibility); a conforming consumer must tolerate them.", "",
                 "| Type | Kind | namespace | processContents |", "| --- | --- | --- | --- |"]
        for owner, kind, ns, pc in pts:
            lines.append(f"| `{owner}` | {kind} | `{ns}` | {pc} |")
        by = {}
        for owner, kind, ns, pc in pts:
            by[(kind, ns)] = by.get((kind, ns), 0) + 1
        lines += ["", "## Summary", ""] + [f"- {k} `{ns}`: {n}" for (k, ns), n in sorted(by.items())]
        sg = ss.substitution_groups()
        lines += ["", "## Substitution groups", ""] + ([f"- `{ss.qstr(h)}`: " + ", ".join(f"`{ss.qstr(m)}`" for m in ms) for h, ms in sg.items()] or ["None declared in this package."])
        self.write("extension-points.md", "\n".join(lines))

    def package_page(self) -> None:
        ss = self.ss
        lines = ["# Package structure", "", "## Namespaces (prefix chosen for display)", "", "| Prefix | URI |", "| --- | --- |"]
        lines += [f"| `{p}` | {u} |" for p, u in ss.namespaces().items()]
        lines += ["", "## Files", "", "| File | Target namespace | Includes | Imports |", "| --- | --- | --- | --- |"]
        for d in ss.docs:
            lines.append(f"| `{Path(d.source).name}`{' (embedded in WSDL)' if d.embedded_in else ''} | {d.target_ns} | "
                         f"{', '.join(d.includes)} | {', '.join(f'{n}<-{l}' for n, l in d.imports)} |")
        lines += ["", "## WSDL", ""]
        for wd in ss.wsdls:
            lines.append(f"### `{Path(wd.source).name}` ({wd.name})")
            lines.append("")
            lines.append(f"- target namespace `{wd.target_ns}`; policies: {', '.join(wd.policies) or 'none'}")
            for pt in wd.port_types.values():
                lines.append(f"- portType `{pt.name[1]}`: {len(pt.operations)} operations, event source={pt.event_source}")
            if not wd.port_types:
                lines.append("- no portTypes (device/discovery marker WSDL only)")
            for b in wd.bindings.values():
                resolved = b.port_type in wd.port_types
                lines.append(f"- binding `{b.name[1]}` for `{ss.qstr(b.port_type)}`: SOAP {b.soap_version}, style={b.style}, "
                             f"{len(b.operations)} operations" + ("" if resolved else " **(portType not resolvable in this WSDL; check the QName prefix)**"))
            for s in wd.services.values():
                for p in s.ports:
                    lines.append(f"- service `{s.name}` port `{p.name}` address `{p.address}` (placeholder)")
            lines.append("")
        lines += ["## Unresolved references", ""]
        lines += [f"- `{Path(a).name}`: {k} `{t}`" for a, k, t in ss.unresolved] or ["None."]
        lines += ["", "## Duplicate definitions", ""] + ([f"- {k} `{ss.qstr(n)}` in `{Path(s).name}`" for k, n, s in ss.duplicates] or ["None."])
        foreign = ss.foreign_namespaces()
        lines += ["", "## Namespaces referenced but not defined here", ""] + ([f"- `{ns}`: {', '.join(sorted(set(v)))}" for ns, v in foreign.items()] or ["None."])
        self.write("package.md", "\n".join(lines))

    def ticket_page(self) -> None:
        ss, prof = self.ss, self.profile
        marks = prof.ticket_markers
        tys = sorted(q for q in ss.complex_types if any(m in q[1] for m in marks))
        lines = ["# Ticket and capability types", "",
                 "Types whose name matches " + ", ".join(f"`{m}`" for m in marks) + ". Vocabulary notes:", ""]
        known_foreign = [ns for ns in ss.foreign_namespaces()]
        mentions = [t for t in ss.simple_types if t[1].lower().find("keyword") >= 0]
        lines.append("- The package defines the ticket as ordinary schema types (below). "
                     "Windows Print Schema (`psf`/`psk`) keywords are " +
                     ("referenced via namespace(s): " + ", ".join(known_foreign) if known_foreign else "**not referenced by any schema in this package**") + ".")
        blobs = [(ss.qstr(q), ss.qstr(p.name)) for q, ct in ss.complex_types.items() for r in ss.effective_rows(ct)
                 for p in [r.particle] if p.kind == "element" and p.name and r.declared_in == q and p.type == (w.XS, "base64Binary") and "Ticket" in p.name[1]]
        if blobs:
            lines.append("- Opaque ticket payloads (base64 blob plus a format string; contents are NOT defined by the package): "
                         + ", ".join(f"`{a}/{b}`" for a, b in blobs) + ".")
        lines += ["", "| Type | Elements | Link |", "| --- | --- | --- |"]
        for q in tys:
            ct = ss.complex_types[q]
            lines.append(f"| `{ss.qstr(q)}` | {len(ss.effective_rows(ct))} | {self.link(q)} |")
        lines.append("")
        for q in tys[:6]:
            lines += ["## Outline: " + ss.qstr(q), ""]
            self.outline(q, 6, (), "", lines)
            lines.append("")
        self.write("ticket.md", "\n".join(lines))

    def elements_page(self) -> None:
        ss = self.ss
        occ: dict[str, list[str]] = {}
        for qn, ct in ss.complex_types.items():
            for r in ss.effective_rows(ct):
                p = r.particle
                if p.kind == "element" and p.name and r.declared_in == qn:
                    occ.setdefault(p.name[1], []).append(f"{qn[1]}:{ss.qstr(p.type) if p.type else 'anon'}")
        lines = ["# Element name index", "", "Every element name declared inside a complex type, with the parent type and its type.", "",
                 "| Element | Parent:Type |", "| --- | --- |"]
        for name in sorted(occ):
            lines.append(f"| `{name}` | {_esc(', '.join(sorted(set(occ[name]))))} |")
        lines += ["", "## Global elements", "", "| Element | Type |", "| --- | --- |"]
        for qn, e in sorted(ss.elements.items()):
            lines.append(f"| `{ss.qstr(qn)}` | {self.link(e.type) if e.type else 'anonymous'} |")
        self.write("elements.md", "\n".join(lines))

    def index_pages(self, pages, ops, concepts) -> None:
        ss = self.ss
        lines = [f"# {self.profile.title}: generated schema reference", "", self.profile.blurb, "",
                 f"- **Namespaces:** " + ", ".join(f"`{u}`" for u in ss.target_namespaces()),
                 f"- **Global elements:** {len(ss.elements)}; **complex types:** {len(ss.complex_types)}; **simple types:** {len(ss.simple_types)}",
                 f"- **WSDL operations:** {len(ss.operations())} (+ {len(ops['ext'])} message-only extension operations)", "",
                 "## Pages", "", "- [Operations](operations/index.md)", "- [Fault codes](faults.md)", "- [Enumerations](enumerations.md)",
                 "- [Attributes](attributes.md)", "- [Extension points](extension-points.md)", "- [Ticket and capability types](ticket.md)",
                 "- [Package structure](package.md)", "- [Element name index](elements.md)", "- `schema-model.json` (machine-readable model)", ""]
        lines += ["## Per-file pages", "", "| Page | File | Types | Elements |", "| --- | --- | --- | --- |"]
        lines += [f"| [{p}]({p}) | `{f}` | {t} | {e} |" for p, f, t, e in pages]
        if concepts:
            lines += ["", "## Concept pages", ""] + [f"- [{c}](concepts/{c}.md)" for c in concepts]
        lines += ["", "All named types also have a page under `types/`.", ""]
        self.write("index.md", "\n".join(lines))
        self.write("00-Overview.md", "\n".join(lines))


def build(ss: SchemaSet, profile: services.ServiceProfile, out_dir: Path) -> list[Path]:
    """Write every generated page plus ``schema-model.json``; return the written paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    g = _Gen(ss, profile, out_dir)
    for sub in ("types", "operations", "concepts"):
        d = out_dir / sub
        if d.is_dir():
            for f in d.glob("*.md"):
                f.unlink()
    for stale in out_dir.glob("[0-9][0-9]-*.md"):
        stale.unlink()
    g.type_pages()
    pages = g.file_pages()
    ops = g.operation_pages()
    concepts = g.concept_pages()
    g.faults_page()
    g.enumerations_page()
    g.attributes_page()
    g.extension_page()
    g.package_page()
    g.ticket_page()
    g.elements_page()
    g.index_pages(pages, ops, concepts)
    model = out_dir / "schema-model.json"
    model.write_text(json.dumps(ss.to_dict(), indent=1, ensure_ascii=False), encoding="utf-8")
    g.written.append(model)
    return g.written


def load_profile_schema(profile: services.ServiceProfile, schema_dir: Path | None = None) -> SchemaSet:
    sdir = schema_dir or profile.schema_dir()
    if not sdir.is_dir():
        raise FileNotFoundError(f"schema directory not found: {sdir} (fetch the package with scripts/Get-WsdSpecs.ps1)")
    dirs = [sdir] + [d for d in profile.search_dirs()[1:] if d.is_dir()]
    ss = SchemaSet()
    for d in dirs:
        ss.add_path(d, search_dirs=dirs)
    return ss


def generate_reference_docs(profile: str | services.ServiceProfile = "print", schema_dir: Path | str | None = None,
                            out_dir: Path | str | None = None) -> list[Path]:
    prof = services.PROFILES[profile] if isinstance(profile, str) else profile
    sdir = Path(schema_dir) if schema_dir else None
    ss = load_profile_schema(prof, sdir)
    return build(ss, prof, Path(out_dir) if out_dir else (sdir or prof.schema_dir()))


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate schema reference pages and schema-model.json from a WSD package.")
    ap.add_argument("--service", default="print", choices=sorted(services.PROFILES))
    ap.add_argument("--schema-dir", default=None, help="directory with the *.xsd/*.wsdl files (default: sibling repo docs/reference/schema)")
    ap.add_argument("--out-dir", default=None, help="output directory (default: the schema directory; ignored by git)")
    args = ap.parse_args(argv)
    for p in generate_reference_docs(args.service, args.schema_dir, args.out_dir):
        print(p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
